import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

// Regenerates src/domain/confusable-letters.ts, the chat filter's table of characters that look like a plain Latin
// letter: run `node --import tsx scripts/confusable-letters.ts`. Two Unicode sources are merged:
// - confusables.txt (UTS #39), every single code point Unicode lists as confusable with one ASCII letter;
// - UnicodeData.txt, every Latin letter with a hook, stroke, curl or other attachment that NFKD leaves alone
//   ("ȵ", "ɼ"), named LATIN ... LETTER X WITH ..., plus the small capitals.
// Characters the filter already reads as the letter (NFKD with marks removed, then lowercased) are left out.
const CONFUSABLES = 'https://www.unicode.org/Public/security/latest/confusables.txt';
const UNICODE_DATA = 'https://www.unicode.org/Public/UCD/latest/ucd/UnicodeData.txt';
const OUTPUT = resolve(import.meta.dirname, '../src/domain/confusable-letters.ts');

const MARKS = /[\p{Mn}\p{Me}\p{Cf}]/gu;
const fold = (text: string) => text.normalize('NFKD').replace(MARKS, '').toLowerCase();
const LATIN_NAME = /^LATIN (?:SMALL |CAPITAL )?LETTER (?:SMALL CAPITAL )?([A-Z])(?: WITH .*| BAR| BELTED| STROKE)?$|^LATIN LETTER SMALL CAPITAL ([A-Z])$/;

async function text(url: string): Promise<string> {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: ${response.status}`);
  return response.text();
}

async function main() {
  const letters = new Map<string, string>();
  const add = (char: string, letter: string) => {
    for (const form of new Set([char, char.toLowerCase()])) {
      if ([...form].length !== 1 || form.codePointAt(0)! < 0x80) continue;
      const folded = fold(form);
      // Already read as the letter, or a ligature or digraph ("ǅ", "ǈ") that NFKD spells out as two letters.
      if (folded === letter || [...folded].length > 1) continue;
      if (!letters.has(form)) letters.set(form, letter);
    }
  };
  for (const line of (await text(CONFUSABLES)).split('\n')) {
    const match = /^([0-9A-F]+) ;\t([0-9A-F ]+?) ;\tMA/.exec(line);
    if (!match) continue;
    const target = match[2]!.split(' ').map(hex => String.fromCodePoint(parseInt(hex, 16))).join('');
    if (/^[A-Za-z]$/.test(target)) add(String.fromCodePoint(parseInt(match[1]!, 16)), target.toLowerCase());
  }
  for (const line of (await text(UNICODE_DATA)).split('\n')) {
    const [hex, name] = line.split(';');
    const match = name ? LATIN_NAME.exec(name) : null;
    if (match) add(String.fromCodePoint(parseInt(hex!, 16)), (match[1] ?? match[2])!.toLowerCase());
  }
  const byLetter = new Map<string, string>();
  for (const [char, letter] of [...letters].sort(([a], [b]) => a.codePointAt(0)! - b.codePointAt(0)!)) byLetter.set(letter, (byLetter.get(letter) ?? '') + char);
  const rows = [...byLetter].sort(([a], [b]) => a.localeCompare(b)).map(([letter, chars]) => `  ${letter}: ${JSON.stringify(chars)},`);
  writeFileSync(OUTPUT, [
    '// Generated by scripts/confusable-letters.ts from Unicode confusables.txt and UnicodeData.txt. Do not edit by hand.',
    '/** For each Latin letter, the characters that look like it and that NFKD does not already turn into it. */',
    'export const CONFUSABLE_LETTERS: Record<string, string> = {',
    ...rows,
    '};',
    '',
  ].join('\n'));
  console.log(`${letters.size} characters written to ${OUTPUT}`);
}

main().catch((error) => { console.error(error); process.exit(1); });
